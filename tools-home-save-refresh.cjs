const assert = require('node:assert/strict');
const fs = require('node:fs');
const { connect } = require('./tools-theme-common.cjs');
(async () => {
  const { browser, page, req } = await connect(9230);
  try {
    const lib = await req('library-load');
    const fixture = structuredClone(lib.themes.find(t => t.editorProject));
    fixture.id = 'qa-home-save-refresh';
    fixture.displayName = fixture.name = '验收_首页保存同步';
    fixture.editorProject.template_id = fixture.id;
    fixture.editorProject.name = fixture.displayName;
    delete fixture.editorProject;
    fixture.category = '壁纸';
    fixture.source = 'local';
    fixture.imageUrl = 'https://media.studio.local/' + fs.readdirSync('artifacts/capture-qa/Library').find(n => n.startsWith('capture-') && n.endsWith('.png'));
    fixture.thumbnailUrl = fixture.imageUrl;
    fixture.sourceWidth = 800; fixture.sourceHeight = 300;
    lib.themes = lib.themes.filter(t => t.id !== fixture.id && t.id !== 'custom-' + fixture.id);
    lib.themes.unshift(fixture);
    await req('library-save', { snapshot: lib });
    const d = (await req('devices')).devices.find(d => d.model === 'D69');
    assert(d, 'D69 required');
    await req('select', { serial: d.serial });
    await req('configure', { serial: d.serial, portrait: false });
    await req('apply-media', { serial: d.serial, themeId: fixture.id });
    await req('configure', { serial: d.serial, playing: false });
    await page.reload();
    await page.waitForTimeout(700);
    const before = (await req('devices')).devices.find(x => x.serial === d.serial);
    await page.getByRole('button', { name: '编辑', exact: true }).click();
    await page.getByText('标题文字', { exact: true }).click();
    await page.getByLabel('主题名称', { exact: true }).fill('验收_首页保存同步_已修改');
    await page.getByRole('button', { name: '保存', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.trim() === '保存' && !b.disabled), null, { timeout: 20000 });
    await page.waitForTimeout(250);
    const after = (await req('devices')).devices.find(x => x.serial === d.serial);
    const item = (await req('library-load')).themes.find(x => x.displayName === '验收_首页保存同步_已修改' && x.editorProject?.template_id === fixture.id);
    assert(item);
    assert.equal(after.themeId, item.id);
    assert.notEqual(item.id, fixture.id);
    assert.equal(after.wantsPlaying, false);
    assert.equal(after.orientation, 'landscape');
    assert.equal(after.themeName, '验收_首页保存同步_已修改');
    assert(item.editorProject.master.length > 1);
    assert.notEqual(after.preview, before.preview);
    assert.equal(await req('refresh-current-media', { serial: d.serial, themeId: item.id, portrait: true }), false);
    await page.getByRole('button', { name: '返回', exact: true }).click();
    assert(await page.getByText('验收_首页保存同步_已修改', { exact: true }).count());
    fs.writeFileSync('artifacts/home-save-refresh-result.json', JSON.stringify({sameThemeId:true, pausedPreserved:true, orientationPreserved:true, newLayerSaved:true, previewChanged:true, homeTitleUpdated:true, staleOrientationRejected:true}, null, 2));
    console.log('PASS home edit -> add layer -> save -> return, updated preview and paused state');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
