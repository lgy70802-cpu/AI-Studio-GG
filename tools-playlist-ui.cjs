const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {chromium}=require('playwright');
(async()=>{
const browser=await chromium.connectOverCDP('http://127.0.0.1:9227'),page=browser.contexts()[0].pages().find(p=>p.url().includes('studio.local')&&!p.url().includes('device-render'));
const req=(command,payload={})=>page.evaluate(({command,payload})=>new Promise((resolve,reject)=>{const id=crypto.randomUUID();const fn=e=>{if(e.data.id!==id)return;window.chrome.webview.removeEventListener('message',fn);e.data.error?reject(Error(e.data.error)):resolve(e.data.result);};window.chrome.webview.addEventListener('message',fn);window.chrome.webview.postMessage({id,command,...payload});}),{command,payload});
let initial=await req('library-load');
initial.playlists=initial.playlists.filter(p=>!p.name.startsWith('验收_UI'));
await req('library-save',{snapshot:initial});await page.reload();await page.waitForTimeout(1000);
await page.getByRole('textbox',{name:'搜索主题与壁纸'}).fill('');
await page.getByRole('button',{name:'轮播列表',exact:true}).click();
await page.getByRole('button',{name:'新建列表',exact:true}).click();
await page.getByLabel('列表名称',{exact:true}).fill('验收_UI列表');
await page.getByRole('button',{name:'创建列表',exact:true}).click();
await page.waitForTimeout(700);
let snapshot=await req('library-load');
const list=snapshot.playlists.find(p=>p.name==='验收_UI列表');assert(list);
await page.getByRole('button',{name:'添加内容',exact:true}).first().click();
const modal=page.getByRole('dialog');
await modal.getByRole('button',{name:'壁纸',exact:true}).click();
await modal.locator('button').filter({hasText:'D92_2557x615_exact'}).click();
await modal.locator('button').filter({hasText:'日落航线'}).click();
await modal.getByRole('button',{name:/加入列表 \(2\)/}).click();
await page.waitForTimeout(600);
snapshot=await req('library-load');
assert.equal(snapshot.playlists.find(p=>p.id===list.id).items.length,2);
await page.getByTitle('修改名称与心情').click();
await page.getByLabel('列表名称',{exact:true}).fill('验收_UI已改名');
await page.getByRole('button',{name:'保存修改',exact:true}).click();
await page.getByRole('button',{name:'下移条目',exact:true}).first().click();
await page.waitForTimeout(600);
snapshot=await req('library-load');
const changed=snapshot.playlists.find(p=>p.id===list.id);
assert.equal(changed.name,'验收_UI已改名');
assert.equal(changed.items[0].themeId,'sunset-skyline');
const durations=page.getByLabel('停留时长数值');
await durations.first().fill('10');await durations.first().press('Tab');
await page.getByRole('button',{name:'应用到全部',exact:true}).click();
await page.waitForTimeout(500);
snapshot=await req('library-load');
assert(snapshot.playlists.find(p=>p.id===list.id).items.every(i=>i.durationSeconds===10));
await durations.nth(1).fill('12');await durations.nth(1).press('Tab');await page.waitForTimeout(500);
snapshot=await req('library-load');
assert.equal(snapshot.playlists.find(p=>p.id===list.id).items[0].durationSeconds,12);
const draggables=page.locator('[draggable=true]');
await draggables.first().dragTo(draggables.nth(1));await page.waitForTimeout(500);
snapshot=await req('library-load');
assert.equal(snapshot.playlists.find(p=>p.id===list.id).items[0].themeId,'cozy-bear-exact');
await page.getByRole('button',{name:'删除当前轮播列表',exact:true}).click();
await page.getByRole('dialog').getByRole('button',{name:/确认删除/}).click();
await page.waitForTimeout(600);
snapshot=await req('library-load');assert(!snapshot.playlists.some(p=>p.id===list.id));
fs.writeFileSync(path.join(__dirname,'artifacts/playlist-qa/ui-actions.json'),JSON.stringify({create:true,addMultiple:true,rename:true,reorder:true,dragReorder:true,unifiedDuration:true,itemDuration:true,delete:true},null,2));
console.log('UI create/add/rename/reorder/delete passed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
