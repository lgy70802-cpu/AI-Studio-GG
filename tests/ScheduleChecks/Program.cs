using System.Text.Json;
using MiraBox.App;
var count=0;
void Check(bool ok,string name){if(!ok)throw new Exception(name);count++;Console.WriteLine("PASS "+name);}
var now=new DateTime(2026,11,25,8,0,10);
var daily=new StudioScheduleDefinition("a","Daily","one",false,"08:00","daily",[],"theme","image",null,true);
var state=new StudioScheduleState{Enabled=true};
Check(state.Collect([daily],now).Count==1,"current minute executes");
Check(state.Collect([daily],now.AddSeconds(10)).Count==0,"same minute deduplicated");
var restored=JsonSerializer.Deserialize<StudioScheduleState>(JsonSerializer.Serialize(state))!;
Check(restored.Collect([daily],now.AddSeconds(20)).Count==0,"restart cannot duplicate receipt");
Check(restored.Collect([daily],now.AddDays(1)).Count==1,"daily repeats on next date");
Check((daily with{RepeatMode="weekdays"}).Matches(now),"weekday matches Wednesday");
Check(!(daily with{RepeatMode="weekends"}).Matches(now),"weekend excludes Wednesday");
Check((daily with{RepeatMode="weekends"}).Matches(now.AddDays(3)),"weekend matches Saturday");
Check((daily with{RepeatMode="custom",Days=[3]}).Matches(now),"custom weekday matches");
Check(!(daily with{RepeatMode="custom",Days=[]}).Matches(now),"empty custom days excluded");
var once=daily with{Id="once",RepeatMode="once"};
state=new(){Enabled=true};
state.Reconcile([once],now.AddMinutes(-2));
Check(state.OnceAt["once"]==now.Date.AddHours(8),"one-off anchored to next occurrence");
Check(state.Collect([once],now).Count==1&&state.Completed.Contains("once"),"one-off completed after reservation");
Check(state.Collect([once],now.AddDays(1)).Count==0,"one-off does not repeat next day");
state=new(){Enabled=false};
Check(state.Collect([daily],now).Count==0,"global disabled freezes schedule");
state=new(){Enabled=true};
var conflict=daily with{Id="b",Portrait=true};
var due=state.Collect([daily,conflict],now);
Check(due.Count==2&&due[0].SkipReason==null&&due[1].SkipReason!=null,"same physical device conflict deterministically skipped");
state=new(){Enabled=true};
Check(state.Collect([daily,daily with{Id="two",DeviceId="two"}],now).All(item=>item.SkipReason==null),"independent devices both execute");
state=new(){Enabled=true,LastChecked=now.AddMinutes(-10)};
Check(state.Collect([daily],now.AddMinutes(3)).Single().SkipReason!=null,"missed old minute logged and skipped");
state=new(){Enabled=true};
state.Reconcile([daily],now);
Check(state.Next(daily,now)==now.Date.AddHours(8),"pending current-minute next trigger");
state.Collect([daily],now);
Check(state.Next(daily,now)==now.Date.AddDays(1).AddHours(8),"next trigger advances after receipt");
var receipt=state.Begin(daily,now,true);state.Finish(receipt,"成功","first frame");
Check(state.History[0].Manual&&state.History[0].Status=="成功","manual run history distinct from automatic");
Check(state.Collect([daily],now).Count==0,"manual history does not erase automatic receipt");
state=new(){Enabled=true};state.Reconcile([once],now);state.Collect([once],now);state.Reset(once,now);
Check(state.Next(once,now)==now.Date.AddDays(1).AddHours(8),"rearmed one-off uses next unclaimed occurrence");
state=new(){Enabled=false};state.Reconcile([once],now.AddMinutes(-3));state.Collect([once],now.AddMinutes(2));state.Enabled=true;
Check(state.Collect([once],now.AddMinutes(3)).Single().SkipReason!=null,"expired one-off recorded after global pause");Console.WriteLine(count+" checks passed");

