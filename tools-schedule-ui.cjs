const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {chromium}=require('playwright');
(async()=>{
const browser=await chromium.connectOverCDP('http://127.0.0.1:9227'),page=browser.contexts()[0].pages().find(p=>p.url().includes('studio.local')&&!p.url().includes('device-render'));
const req=(command,payload={})=>page.evaluate(({command,payload})=>new Promise((resolve,reject)=>{const id=crypto.randomUUID(),fn=e=>{if(e.data.id!==id)return;window.chrome.webview.removeEventListener('message',fn);e.data.error?reject(Error(e.data.error)):resolve(e.data.result);};window.chrome.webview.addEventListener('message',fn);window.chrome.webview.postMessage({id,command,...payload});}),{command,payload});
await page.reload();await page.waitForTimeout(1000);
await page.getByRole('button',{name:'定时切换',exact:true}).click();
await page.getByRole('button',{name:'新建定时规则',exact:true}).first().click();
await page.getByPlaceholder('例如：深夜护眼模式').fill('验收_UI定时');
await page.locator('input[type=time]').fill('23:59');
await page.locator('form').getByRole('button',{name:'工作日',exact:true}).click();
await page.getByRole('button',{name:'添加定时规则',exact:true}).click();
await page.waitForTimeout(700);
let snapshot=await req('library-load');let rule=snapshot.schedules.find(r=>r.title==='验收_UI定时');assert(rule&&rule.repeatMode==='weekdays');
await page.getByRole('button',{name:'切换 验收_UI定时',exact:true}).click();
await page.waitForTimeout(500);
snapshot=await req('library-load');assert.equal(snapshot.schedules.find(r=>r.id===rule.id).enabled,false);
await page.getByRole('button',{name:'编辑 验收_UI定时',exact:true}).click();
await page.getByPlaceholder('例如：深夜护眼模式').fill('验收_UI已编辑');
await page.locator('form').getByRole('button',{name:'周末',exact:true}).click();
await page.getByRole('button',{name:'保存修改',exact:true}).click();
await page.waitForTimeout(500);
snapshot=await req('library-load');assert.equal(snapshot.schedules.find(r=>r.id===rule.id).repeatMode,'weekends');
await page.getByRole('button',{name:'删除 验收_UI已编辑',exact:true}).click();
await page.waitForTimeout(500);
snapshot=await req('library-load');assert(!snapshot.schedules.some(r=>r.id===rule.id));
fs.writeFileSync(path.join(__dirname,'artifacts/schedule-qa/ui-results.json'),JSON.stringify({create:true,weekday:true,toggle:true,edit:true,weekend:true,delete:true},null,2));
console.log('UI create/toggle/edit/delete passed');await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
